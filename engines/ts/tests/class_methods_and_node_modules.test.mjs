import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { compilerOptionsFor, dropped, runTier0 } from '../tier0.ts';

test('compilerOptionsFor resolves node_modules when present and keeps TS2307 for installed packages', () => {
  const dir = mkdtempSync(join(tmpdir(), 'ts-nm-'));
  try {
    mkdirSync(join(dir, 'node_modules', '@types', 'demo'), { recursive: true });
    writeFileSync(join(dir, 'node_modules', '@types', 'demo', 'index.d.ts'), 'export declare function greet(x: string): string;\n');
    mkdirSync(join(dir, 'node_modules', 'demo-pkg'), { recursive: true });
    writeFileSync(join(dir, 'node_modules', 'demo-pkg', 'index.d.ts'), 'export declare const ok: number;\n');

    const opts = compilerOptionsFor(dir);
    assert.ok(opts.typeRoots && opts.typeRoots.some((r) => r.endsWith('@types')));
    assert.equal(opts.types, undefined);

    const candDir = join(dir, 'cand');
    const baseDir = join(dir, 'base');
    mkdirSync(candDir, { recursive: true });
    mkdirSync(baseDir, { recursive: true });
    mkdirSync(join(candDir, 'node_modules', 'demo-pkg'), { recursive: true });
    writeFileSync(join(candDir, 'node_modules', 'demo-pkg', 'index.d.ts'), 'export declare const ok: number;\n');
    writeFileSync(join(candDir, 'a.ts'), "import { ok } from 'demo-pkg';\nexport const v: string = ok;\n");
    writeFileSync(join(baseDir, 'a.ts'), 'export const v: string = "1";\n');

    const res = runTier0({
      schema_version: 1,
      language: 'typescript',
      base_dir: baseDir,
      candidate_dir: candDir,
      changed_files: ['a.ts'],
      budget: {},
    });
    assert.equal(res.ok, false);
    assert.ok(res.findings.some((f) => f.kind === 'typecheck' && f.message.includes('number')));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('engine.ts judges exported ClassDeclaration methods differentially', () => {
  const dir = mkdtempSync(join(tmpdir(), 'ts-cls-'));
  try {
    const baseDir = join(dir, 'base');
    const candDir = join(dir, 'cand');
    const ioDir = join(dir, 'io');
    mkdirSync(baseDir, { recursive: true });
    mkdirSync(candDir, { recursive: true });
    mkdirSync(ioDir, { recursive: true });

    writeFileSync(join(baseDir, 'calc.ts'), 'export class Calc {\n  add(a: number, b: number): number { return a + b; }\n}\n');
    writeFileSync(join(candDir, 'calc.ts'), 'export class Calc {\n  add(a: number, b: number): number { return a - b; }\n}\n');
    writeFileSync(join(ioDir, 'request.json'), JSON.stringify({
      schema_version: 1,
      language: 'typescript',
      base_ref: '0'.repeat(40),
      base_dir: baseDir,
      candidate_dir: candDir,
      changed_files: ['calc.ts'],
      budget: { examples: 20, seed: 42 },
      generators_override: null,
    }));

    const r = spawnSync(process.execPath, ['--no-warnings', '--import', 'tsx', 'engine.ts'], {
      cwd: new URL('..', import.meta.url),
      env: { ...process.env, A2DLC_IO: ioDir },
      encoding: 'utf-8',
    });
    assert.equal(r.status, 0, r.stderr);
    const resp = JSON.parse(readFileSync(join(ioDir, 'response.json'), 'utf-8'));
    const tgt = resp.targets.find((t) => t.target === 'calc.ts::Calc.add');
    assert.ok(tgt, `missing Calc.add target in ${JSON.stringify(resp.targets)}`);
    assert.equal(tgt.verdict, 'FAIL');
    assert.ok(tgt.counterexample);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

// Runs engine.ts over a base/candidate pair ({ "file.ts": "text" } maps) and returns its response.json.
function runEngine(base, cand, changed) {
  const dir = mkdtempSync(join(tmpdir(), 'ts-cls-'));
  try {
    const baseDir = join(dir, 'base');
    const candDir = join(dir, 'cand');
    const ioDir = join(dir, 'io');
    for (const d of [baseDir, candDir, ioDir]) mkdirSync(d, { recursive: true });
    for (const [f, text] of Object.entries(base)) writeFileSync(join(baseDir, f), text);
    for (const [f, text] of Object.entries(cand)) writeFileSync(join(candDir, f), text);
    writeFileSync(join(ioDir, 'request.json'), JSON.stringify({
      schema_version: 1, language: 'typescript', base_ref: '0'.repeat(40), base_dir: baseDir, candidate_dir: candDir,
      changed_files: changed, budget: { examples: 20, seed: 42 }, generators_override: null,
    }));
    const r = spawnSync(process.execPath, ['--no-warnings', '--import', 'tsx', 'engine.ts'], {
      cwd: new URL('..', import.meta.url), env: { ...process.env, A2DLC_IO: ioDir }, encoding: 'utf-8',
    });
    assert.equal(r.status, 0, r.stderr);
    return JSON.parse(readFileSync(join(ioDir, 'response.json'), 'utf-8'));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('an instance method named like a Function.prototype member (valueOf) is judged on the instance, not on the class', () => {
  const src = (k) => `export class Money {\n  cents = 5;\n  valueOf(): number { return this.cents * ${k}; }\n}\n`;
  const resp = runEngine({ 'money.ts': src(2) }, { 'money.ts': src(3) }, ['money.ts']);
  const tgt = resp.targets.find((t) => t.target === 'money.ts::Money.valueOf');
  assert.ok(tgt, `missing Money.valueOf target in ${JSON.stringify(resp.targets)}`);
  assert.equal(tgt.verdict, 'FAIL');
  assert.ok(tgt.counterexample);
});

test('an unchanged instance toString is not failed because another method changed the class source', () => {
  const src = (add, k) => `const K = ${k};\nexport class Calc {\n  add(a: number, b: number): number { return ${add}; }\n  toString(): string { return 'v' + K; }\n}\n`;
  const resp = runEngine({ 'calc.ts': src('a + b', "'k'") }, { 'calc.ts': src('a + b + 0', "'k'.toString()") }, ['calc.ts']);
  const tgt = resp.targets.find((t) => t.target === 'calc.ts::Calc.toString');
  assert.ok(tgt, `missing Calc.toString target in ${JSON.stringify(resp.targets)}`);
  assert.equal(tgt.verdict, 'PASS', JSON.stringify(tgt));
});

test('a static method is still judged on the class', () => {
  const src = (k) => `export class Util {\n  static twice(a: number): number { return a * ${k}; }\n}\n`;
  const resp = runEngine({ 'util.ts': src(2) }, { 'util.ts': src(3) }, ['util.ts']);
  const tgt = resp.targets.find((t) => t.target === 'util.ts::Util.twice');
  assert.ok(tgt, `missing Util.twice target in ${JSON.stringify(resp.targets)}`);
  assert.equal(tgt.verdict, 'FAIL');
});

test('a class whose constructor needs arguments is INCONCLUSIVE and the other targets still get their verdict', () => {
  const src = (k) => `export class Box {\n  constructor(private n: number) { if (n === undefined) throw new Error('need n'); }\n  get(a: number): number { return a + ${k}; }\n}\nexport function f(a: number): number { return a + ${k}; }\n`;
  const resp = runEngine({ 'box.ts': src(1) }, { 'box.ts': src(2) }, ['box.ts']);
  const box = resp.targets.find((t) => t.target === 'box.ts::Box.get');
  assert.ok(box, `missing Box.get target in ${JSON.stringify(resp.targets)}`);
  assert.equal(box.verdict, 'INCONCLUSIVE');
  assert.match(box.reason, /need n/);
  const fn = resp.targets.find((t) => t.target === 'box.ts::f');
  assert.ok(fn, `missing f target in ${JSON.stringify(resp.targets)}`);
  assert.equal(fn.verdict, 'FAIL');
});
